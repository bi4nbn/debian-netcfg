// loadLang 读取持久化的语言设置（文件不存在时保持默认 en）
func loadLang() {
	data, err := os.ReadFile(langFlagPath)
	if err != nil {
		return
	}
	switch strings.TrimSpace(string(data)) {
	case "zh", "en":
		currentLang = strings.TrimSpace(string(data))
	}
}

// saveLang 持久化当前语言设置（无权限时静默忽略）
func saveLang() {
	_ = os.WriteFile(langFlagPath, []byte(currentLang), 0644)
}

func T(key string) string {
	m := enMessages
	if currentLang == "zh" {
		m = zhMessages
	}
	if v, ok := m[key]; ok {
		return v
	}
	// 当前语言缺失时回退中文，两者都缺失时返回 key 本身以便暴露遗漏
	if v, ok := zhMessages[key]; ok {
		return v
	}
	return key
}
